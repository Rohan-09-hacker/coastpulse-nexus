import { IAIProviderAdapter, CompletionRequest, CompletionResponse, StreamChunk } from './adapter.interface.ts';

export class DemoAdapter implements IAIProviderAdapter {
  readonly providerId = 'demo';
  readonly providerName = 'COASTPULSE Deterministic Simulator';
  readonly isDemo = true;

  async initialize(): Promise<void> {
    // Internal simulator requires zero external network dependencies
  }

  async checkHealth(): Promise<{ isHealthy: boolean; message: string; latencyMs?: number }> {
    return {
      isHealthy: true,
      message: 'Demo simulator active (deterministic, zero external API cost).',
      latencyMs: 12,
    };
  }

  async listModels() {
    return [
      {
        id: 'demo-sim-coastal-v1',
        displayName: 'Demo Coastal Triage Sim v1 (Simulated)',
        contextWindow: 32768,
        supportsStreaming: true,
        supportsVision: false,
        isSimulated: true,
      },
    ];
  }

  private generateSimulatedResponse(request: CompletionRequest): string {
    const promptLower = request.prompt.toLowerCase();

    if (request.featureSource === 'coastal' || promptLower.includes('incident') || promptLower.includes('spill') || promptLower.includes('coast')) {
      return `[SIMULATED SCENARIO ASSESSMENT - DEMO ADAPTER]
THREAT LEVEL: CRITICAL
PRIMARY HAZARD: Uncontained marine hydrocarbon plume & tidal drift
VULNERABILITY ASSESSMENT:
- Estuary nursery grounds 1.2 nautical miles southeast
- Wind vector: 14 kts from 315° (NW); drift velocity calculated at 0.6 kts
- Expected shoreline contact window: 2 hours 40 minutes

PROPOSED IMMEDIATE CONTAINMENT ACTIONS:
1. [CONSEQUENTIAL] Deploy 500m absorbent boom curtain across estuary bottleneck (Action ID: act-deploy-boom)
2. [CONSEQUENTIAL] Issue broadcast Notice to Mariners restricting commercial traffic in sector Charlie (Action ID: act-nav-warning)
3. Activate drone surveillance overflight for thermal slick mapping

NOTE: This response is generated by the COASTPULSE Demo Provider for testing and training.`;
    }

    if (request.featureSource === 'workflow' || promptLower.includes('workflow') || promptLower.includes('step')) {
      return `[SIMULATED WORKFLOW STEP OUTPUT]
Input parsed successfully. Intermediate parameters verified.
- Status: Pipeline validated
- Data integrity score: 0.98
- Readiness for downstream processing: Approved`;
    }

    return `[SIMULATED AI RESPONSE - DEMO PROVIDER]
This is a deterministic demonstration response from the COASTPULSE simulator.
Prompt processed: "${request.prompt.slice(0, 80)}..."
All outputs from this provider are explicitly tagged as simulated in database logs and telemetry views.`;
  }

  async generateText(request: CompletionRequest): Promise<CompletionResponse> {
    const start = performance.now();
    // Simulate brief processing latency (150ms - 300ms)
    await new Promise((res) => setTimeout(res, 180));
    const latencyMs = Math.round(performance.now() - start);

    const text = this.generateSimulatedResponse(request);
    const approxWords = text.split(/\s+/).length;
    const promptWords = request.prompt.split(/\s+/).length;

    return {
      text,
      providerId: this.providerId,
      modelId: request.modelId || 'demo-sim-coastal-v1',
      latencyMs,
      promptTokens: Math.round(promptWords * 1.3),
      completionTokens: Math.round(approxWords * 1.3),
      totalTokens: Math.round((promptWords + approxWords) * 1.3),
      estimatedCostUsd: null, // Simulated executions have null real cost
      metricFidelity: 'simulated',
      isSimulated: true,
      status: 'success',
    };
  }

  async generateStream(
    request: CompletionRequest,
    onChunk: (chunk: StreamChunk) => void
  ): Promise<CompletionResponse> {
    const start = performance.now();
    const text = this.generateSimulatedResponse(request);
    const words = text.split(' ');

    let accumulatedText = '';
    for (let i = 0; i < words.length; i++) {
      const wordDelta = (i === 0 ? '' : ' ') + words[i];
      accumulatedText += wordDelta;
      onChunk({
        deltaText: wordDelta,
        done: false,
      });
      // Small streaming delay
      await new Promise((res) => setTimeout(res, 25));
    }

    const latencyMs = Math.round(performance.now() - start);
    const approxWords = accumulatedText.split(/\s+/).length;
    const promptWords = request.prompt.split(/\s+/).length;

    const finalResponse: CompletionResponse = {
      text: accumulatedText,
      providerId: this.providerId,
      modelId: request.modelId || 'demo-sim-coastal-v1',
      latencyMs,
      promptTokens: Math.round(promptWords * 1.3),
      completionTokens: Math.round(approxWords * 1.3),
      totalTokens: Math.round((promptWords + approxWords) * 1.3),
      estimatedCostUsd: null,
      metricFidelity: 'simulated',
      isSimulated: true,
      status: 'success',
    };

    onChunk({
      deltaText: '',
      done: true,
      finalResponse,
    });

    return finalResponse;
  }
}
